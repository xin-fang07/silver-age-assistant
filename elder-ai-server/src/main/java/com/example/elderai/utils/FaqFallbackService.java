    // ==================== 核心方法 ====================

    /**
     * 根据用户问题匹配 FAQ 知识库中的预设回答
     * <p>
     * 遍历关键词映射表，检查用户问题中是否包含某个关键词（大小写不敏感），
     * 匹配到第一个即返回对应回答。全部未匹配则返回默认兜底回答。
     * </p>
     *
     * @param question 用户输入的问题文本
     * @return 匹配到的 FAQ 预设回答，或默认兜底回答
     */
    public String getFaqAnswer(String question) {
        // 参数校验：问题为空时直接返回默认回答
        if (question == null || question.isBlank()) {
            log.debug("用户问题为空，返回默认回答");
            return DEFAULT_ANSWER;
        }

        // 转为小写以便大小写不敏感匹配
        String lowerQuestion = question.toLowerCase();

        // 遍历关键词映射表，查找匹配
        for (Map.Entry<String, String> entry : faqMap.entrySet()) {
            // 关键词可能包含多个，用逗号分隔
            String[] keywords = entry.getKey().split(",");
            for (String keyword : keywords) {
                String lowerKeyword = keyword.trim().toLowerCase();
                // 判断用户问题中是否包含该关键词
                if (lowerQuestion.contains(lowerKeyword)) {
                    log.info("FAQ 匹配成功，问题内容未记录");
                    return entry.getValue();
                }
            }
        }

        // 未匹配到任何关键词，返回默认回答
        log.info("FAQ 未匹配到关键词，返回默认回答");
        return DEFAULT_ANSWER;
    }
